local _, ns = "Curator", CuratorOctoFull

-- (1.14.0, a player's word, the author's after it) The words of the booster bar (its size, its picture, its lights), of
-- the arrows of the pages, of the inventory (one album, the copies of the page) and of the albums complete (a whole level,
-- rubies, a golden booster to choose). They go into the tables of Locale.lua (English keys; a missing one falls back to
-- English).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		if dst[k] == nil then
			dst[k] = v
		end
	end
end

