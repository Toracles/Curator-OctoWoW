-- the auction house, its sheet, its news, its section of the social page, its achievements. They go into the tables
-- of Locale.lua (English keys; a missing one falls back to English; esMX shares the table of esES).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		dst[k] = v
	end
end

