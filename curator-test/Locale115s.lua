local _, ns = "Curator", CuratorOctoFull

-- (1.15.0) The words of the page of the statistics (Rates.lua, UI/Rates.lua). They go into the tables of Locale.lua
-- (English keys; a missing one falls back to English).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		if dst[k] == nil then
			dst[k] = v
		end
	end
end

