-- (1.14.0, his word) The words of the rewards of the levels to choose, one among three (Level.lua: LV:Offers, LV:Choose;
-- UI/Offers.lua; the track, UI/Profile.lua; the screen of a level, UI/LevelUp.lua). They go into the tables of
-- Locale.lua (English keys; a missing one falls back to English; esMX shares the table of esES).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		dst[k] = v
	end
end

