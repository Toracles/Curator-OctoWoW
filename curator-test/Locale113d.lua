-- (1.13.0) The words of the displays of boosters and of the protective cases (Displays.lua, UI/Displays.lua), and of
-- what speaks of them elsewhere (the gift codes, the ledger of the rubies). They go into the tables of Locale.lua
-- (English keys; a missing one falls back to English).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		dst[k] = v
	end
end

