-- (1.13.0) The words of the restoration of the copies at the enchanters (Restore.lua, UI/Restore.lua). They go into the
-- tables of Locale.lua (English keys; a missing one falls back to English).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		dst[k] = v
	end
end

