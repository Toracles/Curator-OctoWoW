-- (1.13.0) The words of the copies (Copies.lua, UI/Copies.lua: each copy on its own, its story, the chooser of the
-- copies that leave), of the inventory (UI/Inventory.lua), of the expertise copy by copy, of the golden quest's lands in
-- its tracker, of the quests of the creatures that give experience and of the players of the Hardcup Saison 3. They go
-- into the tables of Locale.lua (English keys; a missing one falls back to English).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		dst[k] = v
	end
end

