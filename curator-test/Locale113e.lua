-- second test, the contracts redone again (a legendary card at most, the clause of the collection, the register) and the
-- economy of the rubies (the guard of the week); after its third test, an action the game blocked, said, and the reload
-- through a macro of the game. They go into the tables of Locale.lua (English keys; a missing one falls back to English).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		dst[k] = v
	end
end

