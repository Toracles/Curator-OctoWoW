-- (1.14.0, after its first test) The words of the cards of the cases as cards of their own: the cases and the keys in
-- the inventory (UI/CaseInventory.lua), a card alone in the hand and its expertise (UI/CaseView.lua), the albums of
-- their collections and their contracts (UI/CaseAlbum.lua, UI/Album.lua). They go into the tables of Locale.lua
-- (English keys; a missing one falls back to English).
local T = ns.LocaleTables

local function Add(locale, words)
	local dst = T and T[locale]
	if not dst then
		return
	end
	for k, v in pairs(words) do
		dst[k] = v
	end
end

